(function (global) {
  const STORAGE_KEY = "magu-lang";
  const strings = MAGU_STRINGS;

  function detectLang() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === "en" || saved === "es") return saved;
    } catch (e) {}
    const nav = String((typeof navigator !== "undefined" && (navigator.language || navigator.userLanguage)) || "en").toLowerCase();
    return nav.startsWith("es") ? "es" : "en";
  }

  function t(key, lang) {
    const L = lang || MAGU.lang;
    return (strings[L] && strings[L][key]) || (strings.en && strings.en[key]) || "";
  }

  function apply(lang) {
    MAGU.lang = lang;
    document.documentElement.lang = lang;
    document.documentElement.setAttribute("data-lang", lang);

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const val = t(key, lang);
      if (!val) return;
      if (el.childElementCount && el.querySelector(".icon, svg")) {
        const textNode = [...el.childNodes].find((n) => n.nodeType === 3 && n.textContent.trim());
        if (textNode) textNode.textContent = " " + val + " ";
        else el.appendChild(document.createTextNode(" " + val));
      } else {
        el.textContent = val;
      }
    });

    document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
      const val = t(el.getAttribute("data-i18n-alt"), lang);
      if (val) el.setAttribute("alt", val);
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const val = t(el.getAttribute("data-i18n-aria"), lang);
      if (val) el.setAttribute("aria-label", val);
    });

    document.querySelectorAll("[data-i18n-caption]").forEach((el) => {
      const val = t(el.getAttribute("data-i18n-caption"), lang);
      if (val) el.setAttribute("data-caption", val);
    });

    const page = document.body && document.body.getAttribute("data-page");
    if (page) {
      const title = t("meta." + page + ".title", lang);
      const desc = t("meta." + page + ".desc", lang);
      if (title) document.title = title;
      const setMeta = (sel, value) => {
        document.querySelectorAll(sel).forEach((m) => { if (value) m.setAttribute("content", value); });
      };
      setMeta('meta[name="description"]', desc);
      setMeta('meta[property="og:title"]', title);
      setMeta('meta[property="og:description"]', desc);
      setMeta('meta[name="twitter:title"]', title);
      setMeta('meta[name="twitter:description"]', desc);
    }

    document.querySelectorAll(".lang-switch button").forEach((btn) => {
      btn.setAttribute("aria-pressed", btn.getAttribute("data-lang") === lang ? "true" : "false");
    });
  }

  function setLang(lang) {
    if (lang !== "en" && lang !== "es") return;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
    apply(lang);
  }

  function init() {
    apply(detectLang());
    document.querySelectorAll(".lang-switch button").forEach((btn) => {
      btn.addEventListener("click", () => setLang(btn.getAttribute("data-lang")));
    });
  }

  const MAGU = { lang: "en", t, apply, setLang, detectLang, init };
  global.MAGU = MAGU;
})(window);
